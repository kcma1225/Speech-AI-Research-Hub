import type { FastifyPluginAsync, FastifyReply } from "fastify";
import { z } from "zod";
import { requireUser } from "../lib/auth.js";
import { notFound, parse } from "../lib/http.js";
import { outputRevision, slideAccess, slideUrls } from "../lib/slides/access.js";
import { loadManifest, MAX_PAGES, pageImageKey, type PageSize } from "../lib/slides/pages.js";

const versionParams = z.object({ id: z.uuid(), versionId: z.uuid() });
const imageParams = versionParams.extend({ n: z.coerce.number().int().min(1).max(MAX_PAGES), size: z.enum(["thumb", "full"]) });
const slugParams = z.object({ slug: z.string().min(1).max(80), versionId: z.uuid() });
const slugImageParams = slugParams.extend({ n: z.coerce.number().int().min(1).max(MAX_PAGES), size: z.enum(["thumb", "full"]) });
const keyQuery = z.object({ key: z.string().max(200).optional(), r: z.string().max(40).optional() });

const NO_PAGES = "此版本沒有頁面資訊。";
/** Malformed ids, page numbers or sizes are simply "not found" (these URLs are only ever generated by the API). */
function params<T>(schema: z.ZodType<T>, input: unknown, message: string): T {
  const parsed = schema.safeParse(input);
  if (!parsed.success) throw notFound(message);
  return parsed.data;
}
const NO_PAGE = "找不到頁面。";

type PagedVersion = { output_prefix: string; manifest_key: string | null; page_count: number | null };

/**
 * Page manifest + page images of a version (docs/architecture.md "Slide pages"). Session routes see
 * `published` and `review` versions; the by-slug routes (player: public deck, share key or cookie) only
 * `published` ones. Images are version-scoped and never change, so they are cached as immutable.
 */
const slidePages: FastifyPluginAsync = async app => {
  const pagedVersion = async (projectId: string, versionId: string, statuses: string[]) =>
    (await app.db.query<PagedVersion>(
      "SELECT output_prefix,manifest_key,page_count FROM slide_versions WHERE id=$1 AND project_id=$2 AND status=ANY($3::text[])",
      [versionId, projectId, statuses],
    )).rows[0] ?? null;

  const sendManifest = async (reply: FastifyReply, version: PagedVersion | null, versionId: string, url: (n: number, size: PageSize) => string) => {
    const manifest = version?.manifest_key && version.page_count ? await loadManifest(app.storage, version.manifest_key, versionId, url) : null;
    if (!manifest) throw notFound(NO_PAGES);
    return reply.header("Cache-Control", "private, max-age=300").header("X-Content-Type-Options", "nosniff").send(manifest);
  };

  const sendImage = async (reply: FastifyReply, version: PagedVersion | null, n: number, size: PageSize) => {
    if (!version?.page_count || n > version.page_count) throw notFound(NO_PAGE);
    const object = await app.storage.get(pageImageKey(version.output_prefix, n, size));
    if (!object) throw notFound(NO_PAGE);
    reply
      .header("Content-Type", "image/webp")
      .header("Cache-Control", "private, max-age=31536000, immutable")
      .header("X-Content-Type-Options", "nosniff")
      .header("Content-Security-Policy", "default-src 'none'; sandbox");
    if (object.contentLength !== undefined) reply.header("Content-Length", object.contentLength);
    return reply.send(object.body);
  };

  app.get("/slides/:id/versions/:versionId/pages", async (request, reply) => {
    await requireUser(request);
    const { id, versionId } = params(versionParams, request.params, NO_PAGES);
    const version = await pagedVersion(id, versionId, ["published", "review"]);
    const rev = version ? outputRevision(version.output_prefix) : undefined;
    return sendManifest(reply, version, versionId, (n, size) => slideUrls.pageImage(id, versionId, n, size, rev));
  });

  app.get("/slides/:id/versions/:versionId/pages/:n/:size", async (request, reply) => {
    await requireUser(request);
    const { id, versionId, n, size } = params(imageParams, request.params, NO_PAGE);
    return sendImage(reply, await pagedVersion(id, versionId, ["published", "review"]), n, size);
  });

  app.get("/slides/pages/:slug/:versionId", async (request, reply) => {
    const { slug, versionId } = params(slugParams, request.params, NO_PAGES);
    const { key } = parse(keyQuery, request.query);
    const access = await slideAccess(request, slug, key);
    if (!access) throw notFound("簡報不存在。");
    const version = await pagedVersion(access.project.id, versionId, ["published"]);
    const shareKey = access.viaKey ? key : undefined;
    const rev = version ? outputRevision(version.output_prefix) : undefined;
    return sendManifest(reply, version, versionId, (n, size) => slideUrls.slugPageImage(access.project.slug, versionId, n, size, shareKey, rev));
  });

  app.get("/slides/pages/:slug/:versionId/:n/:size", async (request, reply) => {
    const { slug, versionId, n, size } = params(slugImageParams, request.params, NO_PAGE);
    const { key } = parse(keyQuery, request.query);
    const access = await slideAccess(request, slug, key);
    if (!access) throw notFound("簡報不存在。");
    return sendImage(reply, await pagedVersion(access.project.id, versionId, ["published"]), n, size);
  });
};

export default slidePages;
